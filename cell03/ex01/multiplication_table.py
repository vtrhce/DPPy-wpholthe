# รับค่าตัวเลขจากผู้ใช้เพื่อนำมาสร้างแม่สูตรคูณ และแปลงเป็นจำนวนเต็ม (Integer)
number = int(input("Enter a number\n"))

# ใช้ลูปวนค่าตัวคูณตั้งแต่ 0 ถึง 9
i = 0
while i <= 9:
    # คำนวณผลลัพธ์การคูณ
    result = i * number
    # แสดงผลลัพธ์ตามรูปแบบที่โจทย์กำหนด
    print(f"{i} x {number} = {result}")
    # เพิ่มค่าตัวนับทีละ 1 ในแต่ละรอบ
    i += 1