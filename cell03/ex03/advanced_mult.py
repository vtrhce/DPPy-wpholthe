# ลูปภายนอก (Outer loop) ควบคุมแม่สูตรคูณตั้งแต่ 0 ถึง 10
i = 0
while i <= 10:
    j = 0
    row = f"Table de {i}:"
    
    # ลูปภายใน (Inner loop) ควบคุมตัวคูณตั้งแต่ 0 ถึง 10
    while j <= 10:
        row += f" {i * j}"
        j += 1
        
    # แสดงผลลัพธ์ของแต่ละแม่สูตรคูณ
    print(row)
    i += 1