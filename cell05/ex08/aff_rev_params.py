import sys

# ตรวจสอบว่ามีพารามิเตอร์น้อยกว่า 2 ตัวหรือไม่ (รวมชื่อไฟล์สคริปต์แล้วความยาวต้องน้อยกว่า 3)
if len(sys.argv) < 3:
    print("none")
else:
    # ดึงพารามิเตอร์ทั้งหมดตั้งแต่ตัวแรกเป็นต้นไป (ไม่รวมชื่อไฟล์)
    params = sys.argv[1:]
    
    # กลับลำดับพารามิเตอร์ด้วย [::-1] แล้ววนลูปพิมพ์ทีละตัว
    for param in params[::-1]:
        print(param)